function plot_pattern_geometry_summary(cfg, pattern_info)
figure('Name', 'OHD Pattern Geometry', 'Color', 'w');

subplot(1, 3, 1);
imagesc(pattern_binary_table(pattern_info.MAP_TABLE, cfg.n));
colormap(gca, [0.92 0.92 0.92; 0.1 0.35 0.8]);
colorbar('Ticks', [0 1], 'TickLabels', {'Inactive', 'Active'});
xlabel('Position in IM block');
ylabel('Pattern index');
title('Selected Patterns');
set(gca, 'XTick', 1:cfg.n, 'YTick', 1:size(pattern_info.MAP_TABLE, 1));

subplot(1, 3, 2);
D_selected = pattern_info.D(pattern_info.best_set, pattern_info.best_set);
imagesc(D_selected);
axis square;
colorbar;
xlabel('Pattern index');
ylabel('Pattern index');
title('Hamming Distance');
set(gca, 'XTick', 1:size(D_selected, 1), 'YTick', 1:size(D_selected, 1));

subplot(1, 3, 3);
bar(pattern_info.metrics.carrier_usage);
grid on;
xlabel('Position in IM block');
ylabel('Usage count');
title('Carrier Usage');
set(gca, 'XTick', 1:length(pattern_info.metrics.carrier_usage));
end

function plot_random_pattern_validation(cfg, ohd_result, balanced_result, random_result)
if ~has_random_result(random_result)
    return;
end

idx = range_index(cfg.EbN0_dB, 5, 20);
if isempty(idx)
    return;
end

figure('Name', 'Pattern Selection Validation vs Random 5-20 dB', 'Color', 'w');

subplot(1, 2, 1);
semilogy(cfg.EbN0_dB(idx), log_plot_values(ohd_result.ber_im(idx)), '-ro', 'LineWidth', 1.8, 'MarkerSize', 6);
hold on;
if has_optional_result(balanced_result)
    semilogy(cfg.EbN0_dB(idx), log_plot_values(balanced_result.ber_im(idx)), ...
        '-d', 'Color', [0.00 0.45 0.74], 'LineWidth', 1.8, 'MarkerSize', 6);
end
semilogy(cfg.EbN0_dB(idx), log_plot_values(random_result.ber_im_avg(idx)), '-bd', 'LineWidth', 1.6, 'MarkerSize', 6);
grid on;
xlabel('E_b/N_0 (dB)');
ylabel('BER');
title('Total BER');
if has_optional_result(balanced_result)
    legend('OHD', 'B-OHD', 'Random avg', 'Location', 'southwest');
else
    legend('OHD', 'Random avg', 'Location', 'southwest');
end
xlim([min(cfg.EbN0_dB(idx)), max(cfg.EbN0_dB(idx))]);
if has_optional_result(balanced_result)
    apply_log_ylim([ohd_result.ber_im(idx); balanced_result.ber_im(idx); random_result.ber_im_avg(idx)]);
else
    apply_log_ylim([ohd_result.ber_im(idx); random_result.ber_im_avg(idx)]);
end

subplot(1, 2, 2);
semilogy(cfg.EbN0_dB(idx), log_plot_values(ohd_result.ber_idx(idx)), '-ro', 'LineWidth', 1.8, 'MarkerSize', 6);
hold on;
if has_optional_result(balanced_result)
    semilogy(cfg.EbN0_dB(idx), log_plot_values(balanced_result.ber_idx(idx)), ...
        '-d', 'Color', [0.00 0.45 0.74], 'LineWidth', 1.8, 'MarkerSize', 6);
end
semilogy(cfg.EbN0_dB(idx), log_plot_values(random_result.ber_idx_avg(idx)), '-bd', 'LineWidth', 1.6, 'MarkerSize', 6);
grid on;
xlabel('E_b/N_0 (dB)');
ylabel('Index BER');
title('Index BER');
if has_optional_result(balanced_result)
    legend('OHD', 'B-OHD', 'Random avg', 'Location', 'southwest');
else
    legend('OHD', 'Random avg', 'Location', 'southwest');
end
xlim([min(cfg.EbN0_dB(idx)), max(cfg.EbN0_dB(idx))]);
if has_optional_result(balanced_result)
    apply_log_ylim([ohd_result.ber_idx(idx); balanced_result.ber_idx(idx); random_result.ber_idx_avg(idx)]);
else
    apply_log_ylim([ohd_result.ber_idx(idx); random_result.ber_idx_avg(idx)]);
end
end

function bin_table = pattern_binary_table(map_table, n)
bin_table = zeros(size(map_table, 1), n);
for i = 1:size(map_table, 1)
    bin_table(i, map_table(i, :)) = 1;
end
end

function tf = has_random_result(random_result)
tf = ~isempty(random_result) && isfield(random_result, 'applicable') && random_result.applicable;
end

function tf = has_optional_result(result)
tf = ~isempty(result) && isfield(result, 'ber_im');
end

function idx = range_index(x, xmin, xmax)
idx = find(x >= xmin & x <= xmax);
end

function apply_log_ylim(values)
positive_values = values(values > 0);
if isempty(positive_values)
    return;
end

ymin = 10^floor(log10(min(positive_values)));
ymax = 10^ceil(log10(max(positive_values)));
if ymin == ymax
    ymax = ymax * 10;
end
ylim([ymin, ymax]);
end

function values = log_plot_values(values)
positive_values = values(values > 0);
if isempty(positive_values)
    values(:) = 1e-8;
    return;
end

values(values == 0) = min(positive_values) / 10;
end
