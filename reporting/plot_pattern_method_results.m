% Evaluation role: generates report figures that support the thesis argument:
% rate-fair OTFS/OTFS-IM comparison, OHD pattern-selection validation, and
% index/symbol/PER decomposition for deep Chapter 5 discussion.
function plot_pattern_method_results(cfg, ofdm_result, otfs_result, ohd_result, balanced_result, ohd_info, random_result)
% Chapter 5 analysis order for one (n,k) configuration:
% 1) BER overview: prove the baseline story against OFDM and OTFS.
% 2) BER zoom: discuss the useful SNR region where OTFS-IM/OHD matters.
% 3) Error decomposition: explain total BER using index BER, symbol BER, PER.
% 4) OHD geometry: connect Hamming distance and carrier usage to index reliability.
% Optional) Random validation: prove OHD is not equivalent to arbitrary patterns.
%
% The cross-configuration BER-SE figure is intentionally generated by
% plot_se_ber_tradeoff_from_results after multiple saved runs exist.

if nargin == 6
    random_result = [];
elseif nargin < 7
    random_result = [];
end

plot_ber_overview(cfg, ofdm_result, otfs_result, ohd_result, balanced_result);
plot_ber_zoom(cfg, otfs_result, ohd_result, balanced_result);
plot_error_decomposition(cfg, ohd_result, balanced_result, random_result);
plot_pattern_geometry_summary(cfg, ohd_info);
plot_random_pattern_validation(cfg, ohd_result, balanced_result, random_result);
end

function plot_ber_overview(cfg, ofdm_result, otfs_result, ohd_result, balanced_result)
idx = range_index(cfg.EbN0_dB, 0, 20);
if isempty(idx)
    return;
end

figure('Name', 'BER Overview 0-20 dB', 'Color', 'w');
semilogy(cfg.EbN0_dB(idx), log_plot_values(ofdm_result.ber_ofdm(idx)), '-mx', 'LineWidth', 1.8, 'MarkerSize', 7);
hold on;
semilogy(cfg.EbN0_dB(idx), log_plot_values(otfs_result.ber_otfs(idx)), '-ks', 'LineWidth', 1.8, 'MarkerSize', 6);
semilogy(cfg.EbN0_dB(idx), log_plot_values(ohd_result.ber_im(idx)), '-ro', 'LineWidth', 1.8, 'MarkerSize', 6);
legend_entries = {'OFDM-LMMSE', 'OTFS', 'OHD OTFS-IM'};
plot_values = [ofdm_result.ber_ofdm(idx); otfs_result.ber_otfs(idx); ohd_result.ber_im(idx)];
if has_optional_result(balanced_result)
    semilogy(cfg.EbN0_dB(idx), log_plot_values(balanced_result.ber_im(idx)), ...
        '-d', 'Color', [0.00 0.45 0.74], 'LineWidth', 1.8, 'MarkerSize', 6);
    legend_entries{end+1} = 'B-OHD OTFS-IM';
    plot_values = [plot_values; balanced_result.ber_im(idx)];
end
grid on;
xlabel('E_b/N_0 (dB)');
ylabel('BER');
title('BER Overview: OFDM-LMMSE, OTFS, and OTFS-IM');
legend(legend_entries, 'Location', 'southwest');
xlim([min(cfg.EbN0_dB(idx)), max(cfg.EbN0_dB(idx))]);
apply_log_ylim(plot_values);
end

