% Evaluation role: legacy OHD-only result printer. Kept for quick checks of
% OHD total BER, index BER, symbol BER, and pattern error rate.
function print_ohd_results(cfg, otfs_result, im_result, random_result)
% Prints the final OTFS/OHD/random OTFS-IM result tables.

has_random = nargin >= 4 && ~isempty(random_result) && isfield(random_result, 'applicable') && random_result.applicable;

fprintf('\n========================================================\n');
fprintf('                 OHD OTFS-IM RESULT ANALYSIS            \n');
fprintf('========================================================\n');
fprintf('Baseline OTFS SE: %.2f bits/symbol\n', cfg.se_otfs);
fprintf('OHD OTFS-IM SE (n=%d,k=%d): %.2f bits/symbol\n', cfg.n, cfg.k, cfg.se_im);
fprintf('Reduction: %.1f%%\n', (1 - cfg.se_im/cfg.se_otfs)*100);

if has_random
    fprintf('Random baseline: %d tables, %d frames/table\n', cfg.num_random_tables, cfg.N_fram_random);
    fprintf('\n==============================================================\n');
    fprintf('Eb/N0 | BER OTFS | BER OHD-IM | BER Random-IM(avg)\n');
    for i = 1:length(cfg.EbN0_dB)
        fprintf('%5d | %8.5f | %10.5f | %18.5f\n', ...
            cfg.EbN0_dB(i), ...
            otfs_result.ber_otfs(i), ...
            im_result.ber_im(i), ...
            random_result.ber_im_avg(i));
    end

    fprintf('\n========================================================================================\n');
    fprintf('Eb/N0 | OHD Index | Rand Index | OHD Symbol | Rand Symbol | OHD Pattern | Rand Pattern\n');
    for i = 1:length(cfg.EbN0_dB)
        fprintf('%5d | %9.5f | %10.5f | %10.5f | %11.5f | %11.5f | %12.5f\n', ...
            cfg.EbN0_dB(i), ...
            im_result.ber_idx(i), ...
            random_result.ber_idx_avg(i), ...
            im_result.ber_sym(i), ...
            random_result.ber_sym_avg(i), ...
            im_result.per_pattern(i), ...
            random_result.per_pattern_avg(i));
    end
else
    if nargin >= 4
        fprintf('Random baseline: not applicable. %s\n', random_result.reason);
    end

    fprintf('\n=====================================================================\n');
    fprintf('Eb/N0 | BER OTFS | BER OTFS-IM | Index BER | Symbol BER | Pattern ER\n');
    for i = 1:length(cfg.EbN0_dB)
        fprintf('%5d | %8.5f | %11.5f | %9.5f | %10.5f | %10.5f\n', ...
            cfg.EbN0_dB(i), ...
            otfs_result.ber_otfs(i), ...
            im_result.ber_im(i), ...
            im_result.ber_idx(i), ...
            im_result.ber_sym(i), ...
            im_result.per_pattern(i));
    end
end
end
