function print_full_grid_results(base_cfg, qpsk_cfg, conventional_ask_cfg, ...
    ask_cfg, otfs_result, qpsk_result, conventional_ask_result, ask_result)
% PRINT_FULL_GRID_RESULTS in tốc độ, BER và các chỉ số kiểm tra máy thu.
% Bước 1: In bit/frame, hiệu suất phổ và cấu hình từng nhánh.
% Bước 2: In Index BER, Symbol BER, Total BER tại từng Eb/N0.
% Bước 3: In lỗi chọn pattern và kết quả trước/sau two-swap của nhánh QPSK.

fprintf('\n=========================================================================\n');
fprintf('                       RATE AND SPECTRAL EFFICIENCY                       \n');
fprintf('=========================================================================\n');
fprintf('OTFS-QPSK          : %3d bits/frame, SE = %.4f bit/RE\n', ...
    base_cfg.total_bits_otfs, base_cfg.se_otfs);
print_variant(qpsk_cfg);
print_variant(conventional_ask_cfg);
print_variant(ask_cfg);
fprintf('Conventional 4-ASK: ratio=%.2f, minimum magnitude=%.4f\n', ...
    base_cfg.ask_conventional_ratio, ...
    min(abs(conventional_ask_cfg.data_alphabet)));
fprintf('Modified 4-ASK    : ratio=%.2f, minimum magnitude=%.4f\n', ...
    base_cfg.ask_ratio, min(abs(ask_cfg.data_alphabet)));
fprintf('Frames per SNR     : %d\n', base_cfg.N_fram);
fprintf('MP parameters      : iterations=%d, damping=%.2f\n', ...
    base_cfg.mp_iterations, base_cfg.mp_damping);
fprintf('Index mapping      : NBC combinatorial rank/unrank\n');
fprintf('Symbol positioning : pattern-dependent labels\n');
fprintf('QPSK refinement    : up-to-%d-swap residual search, boundary=%d\n', ...
    qpsk_cfg.refinement_max_swaps, qpsk_cfg.refinement_boundary_size);

fprintf('\n=======================================================================================================\n');
fprintf(' Eb/N0 | System             | Index BER  | Symbol BER | Total BER  | Support ER | Invalid pattern\n');
fprintf('-------------------------------------------------------------------------------------------------------\n');
for i = 1:numel(base_cfg.EbN0_dB)
    fprintf('%6.1f | %-18s | %10s | %10.4e | %10.4e | %10s | %15s\n', ...
        base_cfg.EbN0_dB(i), 'OTFS-QPSK', 'N/A', ...
        otfs_result.ber_total(i), otfs_result.ber_total(i), 'N/A', 'N/A');
    print_ber_row(base_cfg.EbN0_dB(i), 'QPSK-NBC', qpsk_result, i);
    print_ber_row(base_cfg.EbN0_dB(i), 'Conventional 4-ASK', ...
        conventional_ask_result, i);
    print_ber_row(base_cfg.EbN0_dB(i), 'Modified 4-ASK', ask_result, i);
    fprintf('-------------------------------------------------------------------------------------------------------\n');
end
fprintf('=======================================================================================================\n');
fprintf('Note: an invalid rank is declared as an all-zero index word.\n');

fprintf('\nQPSK receiver diagnostics\n');
fprintf(' Eb/N0 | Support ER | Avg swaps/frame | Activity margin | Actual symbol BER | Oracle-support BER\n');
for i = 1:numel(base_cfg.EbN0_dB)
    fprintf('%6.1f | %10.4f | %15.4f | %15.4e | %17.4e | %18.4e\n', ...
        base_cfg.EbN0_dB(i), qpsk_result.support_error_rate(i), ...
        qpsk_result.avg_support_swaps(i), ...
        qpsk_result.avg_activity_margin(i), ...
        qpsk_result.ber_symbol(i), qpsk_result.oracle_symbol_ber(i));
end
fprintf('Margin < 0 means at least one inactive position outranks an active position.\n');

fprintf('\nQPSK local-support refinement summary\n');
fprintf(' Eb/N0 | Initial index | Refined index | Initial support | Refined support | Fixed | Broken | Improved/Worsened\n');
fprintf('-------------------------------------------------------------------------------------------------------------\n');
for i = 1:numel(base_cfg.EbN0_dB)
    fprintf('%6.1f | %13.4e | %13.4e | %15.4f | %15.4f | %5d | %6d | %8d/%8d\n', ...
        base_cfg.EbN0_dB(i), qpsk_result.initial_index_ber(i), ...
        qpsk_result.ber_index(i), ...
        qpsk_result.initial_support_error_rate(i), ...
        qpsk_result.support_error_rate(i), ...
        qpsk_result.refinement_fixed(i), ...
        qpsk_result.refinement_broken(i), ...
        qpsk_result.refinement_improved(i), ...
        qpsk_result.refinement_worsened(i));
end
end

function print_ber_row(ebn0, name, result, i)
% In một dòng kết quả OTFS-IM tại một giá trị Eb/N0.
fprintf('%6.1f | %-18s | %10.4e | %10.4e | %10.4e | %10.4f | %15.4f\n', ...
    ebn0, name, result.ber_index(i), result.ber_symbol(i), ...
    result.ber_total(i), result.support_error_rate(i), ...
    result.invalid_pattern_rate(i));
end

function print_variant(cfg)
% In tốc độ frame, SE, K và xác suất active/zero của một nhánh.
fprintf('%-18s : %3d bits/frame, SE = %.4f bit/RE\n', ...
    cfg.name, cfg.lambda, cfg.se_im);
fprintf('  K=%d, index=%d bits, symbol=%d bits, P(active)=%.4f, P(zero)=%.4f\n', ...
    cfg.K_active, cfg.b_index, cfg.b_symbol, ...
    cfg.K_active/cfg.N_grid, 1-cfg.K_active/cfg.N_grid);
end
