function print_full_grid_results(base_cfg, qam16_cfg, ...
    otfs_result, qam16_result)
% PRINT_FULL_GRID_RESULTS in tốc độ và BER của hai hệ 16-QAM.
% Hệ OTFS-IM dùng NBC trên toàn lưới và không dùng two-swap refinement.

fprintf('\n=========================================================================\n');
fprintf('                       RATE AND SPECTRAL EFFICIENCY                       \n');
fprintf('=========================================================================\n');
fprintf('OTFS-16QAM          : %3d bits/frame, SE = %.4f bit/RE\n', ...
    base_cfg.total_bits_otfs, base_cfg.se_otfs);
fprintf('OTFS-IM NBC          : %3d bits/frame, SE = %.4f bit/RE\n', ...
    qam16_cfg.lambda, qam16_cfg.se_im);
fprintf('  K=%d, index=%d bits, symbol=%d bits, P(active)=%.4f, P(zero)=%.4f\n', ...
    qam16_cfg.K_active, qam16_cfg.b_index, qam16_cfg.b_symbol, ...
    qam16_cfg.K_active/qam16_cfg.N_grid, ...
    1-qam16_cfg.K_active/qam16_cfg.N_grid);
fprintf('Frames per SNR      : %d\n', base_cfg.N_fram);
fprintf('MP parameters       : iterations=%d, damping=%.2f\n', ...
    base_cfg.mp_iterations, base_cfg.mp_damping);
fprintf('Index mapping       : NBC combinatorial rank/unrank\n');
fprintf('Support refinement  : disabled\n');

fprintf('\n===============================================================================================\n');
fprintf(' Eb/N0 | System             | Index BER  | Symbol BER | Total BER  | Support ER | Invalid pattern\n');
fprintf('-----------------------------------------------------------------------------------------------\n');
for i = 1:numel(base_cfg.EbN0_dB)
    fprintf('%6.1f | %-18s | %10s | %10.4e | %10.4e | %10s | %15s\n', ...
        base_cfg.EbN0_dB(i), 'OTFS-16QAM', 'N/A', ...
        otfs_result.ber_total(i), otfs_result.ber_total(i), 'N/A', 'N/A');
    fprintf('%6.1f | %-18s | %10.4e | %10.4e | %10.4e | %10.4f | %15.4f\n', ...
        base_cfg.EbN0_dB(i), 'OTFS-IM NBC', ...
        qam16_result.ber_index(i), qam16_result.ber_symbol(i), ...
        qam16_result.ber_total(i), qam16_result.support_error_rate(i), ...
        qam16_result.invalid_pattern_rate(i));
    fprintf('-----------------------------------------------------------------------------------------------\n');
end
fprintf('===============================================================================================\n');
fprintf('Note: an invalid rank is declared as an all-zero index word.\n');

fprintf('\nOTFS-IM NBC receiver diagnostics\n');
fprintf(' Eb/N0 | Support ER | Avg wrong positions | Activity margin | Symbol BER | Oracle symbol BER\n');
for i = 1:numel(base_cfg.EbN0_dB)
    fprintf('%6.1f | %10.4f | %19.4f | %15.4e | %10.4e | %17.4e\n', ...
        base_cfg.EbN0_dB(i), qam16_result.support_error_rate(i), ...
        qam16_result.avg_support_swaps(i), ...
        qam16_result.avg_activity_margin(i), ...
        qam16_result.ber_symbol(i), qam16_result.oracle_symbol_ber(i));
end
end
